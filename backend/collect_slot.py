"""키워드가 하루 중 **몇 시에 수집되는가** — 그 규칙 한 곳.

## 왜 시간대로 나누나

한 IP 에서 짧은 시간에 몰아 치면 네이버가 막는다(2026-08-05 실사고 — 6시간에 3,800여 회로
IP 차단). 그래서 수집을 24시간에 흩뿌리고, 키워드마다 **글자에서 계산한 고정 슬롯**을 준다.
같은 키워드는 언제나 같은 시각에 돈다(안정 해시).

## 하루를 어떻게 나누나 (2026-09-23 대표 확정 · 종전 규칙 교체)

대표 지시 원문: 「순위 수집기는 전일 데이터를 보여주는게 맞지 않아? … 우리는 기록이 우선이라 당일 봐야 할
필요성은 없어. 수집기 자체의 용도가 기록 목적인데 안전하고 정확한게 우선이야. … 고정 아이피로 별도 분리
했으니까 낮에 작업량이 더 많은게 안전해 보여. 24시간으로 돌아가는건데 왜 15시간 동안만 측정하는거야?」

⇒ **모든 키워드를 24시간에 나눈다. 8~22시(사람이 깨어 있는 15시간)에는 한 시간에 두 몫, 나머지 9시간에는 한 몫.**
   몫은 39칸(15×2 + 9×1)이고 키워드 글자 해시로 한 칸을 고른다 — 같은 키워드는 매일 같은 시각이다.
   594개 기준 낮 시간당 약 30개 · 밤 약 15개(두 대 합). 업체 키워드·추적 상품 키워드를 가르지 않는다.

종전 규칙(2026-08-05 ~ 09-23): 업체 키워드는 0~14시, 추적 상품 전용은 15~23시. 이유는 「우선인 것 먼저」와
「① 전산이 08:40 에 순위를 가져가니 그 전에 재 둔다」였다. ⚠️ **바뀐 뒤로 ① 이 08:40 에 가져가는 순위는
대부분 전일 측정값이다** — 대표 확정 「기록이 우선 · 전일 데이터를 보여 주는 것이 맞다」(CLAUDE.md 경계 원칙에 기록).

⚠️ **이 식을 바꾼 날 하루는 키워드 시각이 한꺼번에 이동한다.** 이미 지나간 시각으로 옮겨진 키워드는
   수집기가 「밀린 몫」으로 그날 안에 따라잡는다(collector.get_collect_keywords 의 overdue).

## 왜 파일을 따로 뒀나 (split_rule.py 와 같은 이유)

① 쓰는 곳이 **둘**이다 — 수집 배분(collector)과 화면의 「언제 수집되나」 안내(client_dashboard).
   두 곳이 다른 식을 쓰면 화면이 거짓말을 한다.
② 배포 게이트 환경에 fastapi 가 없어 collector.py 를 임포트할 수 없다.
   규칙이 거기 있으면 **검사할 방법이 없다.** 여기는 표준 라이브러리만 쓴다.
"""

import zlib

# 사람이 깨어 있는 시간 — 이 시간에는 한 시간에 두 몫을 배정한다(대표 확정 2026-09-23 「8시~22시」).
DAY_HOURS = tuple(range(8, 23))      # 8,9,…,22 (15시간)
DAY_WEIGHT = 2
NIGHT_WEIGHT = 1
# 칸 → 시각 표. 칸 수 = 15×2 + 9×1 = 39.
_BUCKETS = tuple(h for h in range(24) for _ in range(DAY_WEIGHT if h in DAY_HOURS else NIGHT_WEIGHT))

# ⚠️ 종전 이름을 남겨 둔다 — collector 가 가져가고(표시용), 지우면 import 가 깨진다.
#    슬롯 계산에는 더 이상 쓰지 않는다.
PRIORITY_HOURS = 15
LATE_HOURS = 24 - PRIORITY_HOURS


def slot_of(keyword: str, priority: bool = True) -> int:
    """키워드 → 수집 시간대(0~23). 문자열이 같으면 항상 같은 값(안정 해시).

    ⚠️ `priority` 는 옛 호출 모양을 위해 받기만 한다 — 2026-09-23 부터 업체 키워드·추적 상품 키워드를
       같은 표로 나눈다(대표 확정 「24시간에 · 낮에 더 많이」).
    ⚠️ 이 식을 바꾸면 **모든 키워드의 수집 시각이 한꺼번에 이동한다.**
       그날 하루는 이미 지나간 슬롯으로 재배정된 키워드가 통째로 밀린다.
    """
    h = zlib.crc32((keyword or "").encode("utf-8"))
    return _BUCKETS[h % len(_BUCKETS)]


def slot_label(hour: int) -> str:
    """사람이 읽는 시각 — 「오후 5시경」.

    ⚠️ 「몇 분」까지 말하지 않는다. 슬롯은 그 시간대 안에서 순서가 정해지고,
       앞 시간대가 밀리면 뒤로 미뤄지기도 한다. 지킬 수 없는 약속은 하지 않는다.
    """
    try:
        h = int(hour)
    except Exception:
        return ""
    h %= 24
    if h == 0:
        return "자정 무렵"
    if h < 12:
        return f"오전 {h}시경"
    if h == 12:
        return "정오 무렵"
    if h < 18:
        return f"오후 {h - 12}시경"
    return f"밤 {h - 12}시경"


def wait_hint(keyword: str, priority: bool, now_hour=None) -> str:
    """「오후 5시경 수집」처럼 화면에 그대로 쓸 한 줄.

    이미 그 시각이 지났으면 「오늘 안에 수집」으로 바꾼다 — 지난 시각을 앞으로 올 것처럼
    적으면 그게 더 헷갈린다(밀린 것은 그날 안에 따라잡는 구조다).
    """
    s = slot_of(keyword, priority)
    if now_hour is not None:
        try:
            if int(now_hour) > s:
                return "오늘 안에 수집"
        except Exception:
            pass
    return f"{slot_label(s)} 수집"
